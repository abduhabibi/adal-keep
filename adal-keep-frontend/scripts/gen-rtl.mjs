#!/usr/bin/env node
/**
 * Arabic reads right to left (html[dir="rtl"], set by src/lib/i18n.js). Flex rows, text and
 * inline layout turn by themselves; Tailwind's physical classes (ml-2, left-0, text-left,
 * rounded-l-lg …) do not. This writes src/rtl.css: for every such class used in src/**.jsx
 * a rule that applies in RTL only and puts it on the other side.
 *   node scripts/gen-rtl.mjs        (run again when new left/right classes are added)
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const SRC = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src')
const files = []
const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) f.isDirectory() ? walk(path.join(d, f.name)) : /\.(jsx|js|html)$/.test(f.name) && files.push(path.join(d, f.name)) }
walk(SRC); files.push(path.join(SRC, '..', 'index.html'))
const text = files.map(f => fs.readFileSync(f, 'utf8')).join('\n')

const BP = { sm: 640, md: 768, lg: 1024, xl: 1280, '2xl': 1536 }
const val = (v) => {
  if (v === 'auto') return 'auto'; if (v === 'px') return '1px'; if (v === 'full') return '100%'
  if (/^\d+(\.\d+)?$/.test(v)) return `${Number(v) * 0.25}rem`
  if (/^\d+\/\d+$/.test(v)) { const [a, b] = v.split('/').map(Number); return `${(a / b * 100).toFixed(6).replace(/\.?0+$/, '')}%` }
  const m = /^\[(.+)\]$/.exec(v); if (m && /^[\d.]+(px|rem|em|%|vw|vh)$/.test(m[1])) return m[1]
  return null
}
const flip = { l: 'r', r: 'l' }
const rules = new Map()
const add = (prefix, cls, decl) => { const k = `${prefix}|${cls}`; if (!rules.has(k)) rules.set(k, { prefix, cls, decl }) }

const tokens = new Set(text.match(/(?:(?:sm|md|lg|xl|2xl):)?-?(?:m[lr]|p[lr]|left|right)-(?:\[[^\]\s"'`]+\]|[\w./]+)|(?:(?:sm|md|lg|xl|2xl):)?(?:text-(?:left|right)|border-[lr](?:-\d+)?|rounded-[lr](?:-[\w]+)?|-translate-x-full|translate-x-full|float-(?:left|right)|(?:sm|md|lg|xl|2xl):?-translate-x-full)(?![\w-])/g) || [])
for (const t of tokens) {
  const [, bp, c] = /^(?:(sm|md|lg|xl|2xl):)?(.+)$/.exec(t)
  let m
  if ((m = /^(-?)(m|p)([lr])-(.+)$/.exec(c))) {
    const v = val(m[4]); if (v == null) continue
    const prop = m[2] === 'm' ? 'margin' : 'padding', neg = m[1] ? '-' : ''
    add(bp, t, `${prop}-${m[3] === 'l' ? 'left' : 'right'}:0;${prop}-${m[3] === 'l' ? 'right' : 'left'}:${neg}${v}`.replace(':-auto', ':auto'))
  } else if ((m = /^(-?)(left|right)-(.+)$/.exec(c))) {
    const v = val(m[3]); if (v == null) continue
    add(bp, t, `${m[2]}:auto;${m[2] === 'left' ? 'right' : 'left'}:${m[1]}${v}`)
  } else if (c === 'text-left') add(bp, t, 'text-align:right')
  else if (c === 'text-right') add(bp, t, 'text-align:left')
  else if (c === 'float-left') add(bp, t, 'float:right')
  else if (c === 'float-right') add(bp, t, 'float:left')
  else if ((m = /^border-([lr])(?:-(\d+))?$/.exec(c))) {
    const w = m[2] === undefined ? '1px' : `${m[2]}px`
    add(bp, t, `border-${m[1] === 'l' ? 'left' : 'right'}-width:0;border-${flip[m[1]] === 'l' ? 'left' : 'right'}-width:${w};border-${flip[m[1]] === 'l' ? 'left' : 'right'}-style:solid;border-${flip[m[1]] === 'l' ? 'left' : 'right'}-color:inherit`)
  } else if ((m = /^rounded-([lr])(?:-(\w+))?$/.exec(c))) {
    const R = { none: '0', sm: '0.125rem', md: '0.375rem', lg: '0.5rem', xl: '0.75rem', '2xl': '1rem', '3xl': '1.5rem', full: '9999px', undefined: '0.25rem' }[m[2]]
    if (R == null) continue
    const a = m[1] === 'l'
    add(bp, t, a ? `border-top-left-radius:0;border-bottom-left-radius:0;border-top-right-radius:${R};border-bottom-right-radius:${R}` : `border-top-right-radius:0;border-bottom-right-radius:0;border-top-left-radius:${R};border-bottom-left-radius:${R}`)
  } else if (/translate-x-full$/.test(c)) add(bp, t, `--tw-translate-x:${c.startsWith('-') ? '100%' : '-100%'}`)
}

const esc = (s) => s.replace(/[^\w-]/g, ch => `\\${ch}`)
let out = '/* Generated by scripts/gen-rtl.mjs — Arabic (html[dir="rtl"]) puts left/right classes on the other side. Do not edit. */\n'
const group = new Map()
for (const { prefix, cls, decl } of [...rules.values()].sort((a, b) => a.cls.localeCompare(b.cls))) {
  const k = prefix || ''; if (!group.has(k)) group.set(k, [])
  group.get(k).push(`html[dir="rtl"] .${esc(cls)}{${decl}}`)
}
out += (group.get('') || []).join('\n') + '\n'
for (const bp of Object.keys(BP)) if (group.has(bp)) out += `@media (min-width:${BP[bp]}px){\n${group.get(bp).join('\n')}\n}\n`
// A flipped '-translate-x-full' (specificity 0,2,1) must not beat the wide-screen 'md:translate-x-0': the sidebar stayed off-screen in Arabic.
out += '@media (min-width:768px){\nhtml[dir="rtl"] .md\\:translate-x-0{--tw-translate-x:0px}\n}\n'
// the page itself
out += 'html[dir="rtl"] body{direction:rtl}\nhtml[dir="rtl"] [translate="no"]{unicode-bidi:plaintext}\n'
fs.writeFileSync(path.join(SRC, 'rtl.css'), out)
console.log(`rtl.css: ${rules.size} rules`)
